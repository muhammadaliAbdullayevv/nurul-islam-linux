export function getLocalizedHifzVerse(verse: HifzVerseItem, lang: AppLanguage): {
  transliteration: string;
  meaning: string;
} {
  if (lang === 'uz_cyr') {
    return {
      transliteration: latinToCyrillicUz(verse.translitUz),
      meaning: latinToCyrillicUz(verse.meaningUz),
    };
  }
  if (lang === 'ru') {
    return {
      transliteration: latinToCyrillicUz(verse.translitUz),
      meaning: verse.meaningRu,
    };
  }
  if (lang === 'en') {
    return {
      transliteration: verse.translitUz,
      meaning: verse.meaningEn,
    };
  }
  return {
    transliteration: verse.translitUz,
    meaning: verse.meaningUz,
  };
}
